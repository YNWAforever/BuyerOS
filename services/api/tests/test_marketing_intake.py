def test_database_commit_rejection_rolls_back_lead_and_challenge(api):
    challenge_id = challenge(api)
    age_challenge(challenge_id, 3)
    body = payload(challenge_id, name="Commit failure probe")
    owner = os.environ["BUYEROS_MARKETING_TEST_OWNER_DSN"]
    with psycopg.connect(owner) as connection:
        connection.execute("CREATE FUNCTION marketing_intake.synthetic_commit_failure() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'synthetic deferred commit failure' USING ERRCODE='23514'; END $$")
        connection.execute("CREATE CONSTRAINT TRIGGER synthetic_commit_failure AFTER INSERT ON marketing_intake.leads DEFERRABLE INITIALLY DEFERRED FOR EACH ROW WHEN (NEW.name = 'Commit failure probe') EXECUTE FUNCTION marketing_intake.synthetic_commit_failure()")
    try:
        result = post(api, body)
        assert result.status_code == 503
        assert result.json() == {"code": "intake_unavailable", "retryable": True}
        with psycopg.connect(owner) as connection:
            assert connection.execute("SELECT count(*) FROM marketing_intake.leads WHERE email=%s", (body["email"],)).fetchone()[0] == 0
            assert connection.execute("SELECT consumed FROM marketing_intake.challenges WHERE id=%s", (challenge_id,)).fetchone()[0] is False
    finally:
        with psycopg.connect(owner) as connection:
            connection.execute("DROP TRIGGER synthetic_commit_failure ON marketing_intake.leads")
            connection.execute("DROP FUNCTION marketing_intake.synthetic_commit_failure()")


def test_concurrent_same_key_creates_one_committed_receipt(api):
    challenge_id = challenge(api)
    age_challenge(challenge_id, 3)
    body, key = payload(challenge_id), str(uuid4())
    with ThreadPoolExecutor(max_workers=4) as workers:
        responses = list(workers.map(lambda _: post(api, body, key), range(4)))
    assert sorted(item.status_code for item in responses) == [200, 200, 200, 201]
    assert len({item.json()["receipt_id"] for item in responses}) == 1
    with psycopg.connect(os.environ["BUYEROS_MARKETING_TEST_OWNER_DSN"]) as connection:
        assert connection.execute("SELECT count(*) FROM marketing_intake.leads WHERE idempotency_key=%s", (key,)).fetchone()[0] == 1


def test_concurrent_email_budget_is_atomic(api, monkeypatch):
    monkeypatch.setenv("BUYEROS_MARKETING_EMAIL_PER_DAY", "1")
    email = f"concurrent-{uuid4().hex}@example.test"
    bodies = [payload(challenge(api), email=email) for _ in range(2)]
    for body in bodies:
        age_challenge(body["challenge_id"], 3)
    with ThreadPoolExecutor(max_workers=2) as workers:
        responses = list(workers.map(lambda body: post(api, body), bodies))
    assert sorted(item.status_code for item in responses) == [201, 429]


def test_durable_email_and_global_limits_across_instances(api, monkeypatch):
    monkeypatch.setenv("BUYEROS_MARKETING_EMAIL_PER_DAY", "1")
    email = f"budget-{uuid4().hex}@example.test"
    first = challenge(api); age_challenge(first, 3)
    body, key = payload(first, email=email), str(uuid4())
    assert post(api, body, key).status_code == 201
    second = challenge(api); age_challenge(second, 3)
    assert post(api, payload(second, email=email)).status_code == 429
    assert post(api, body, key).status_code == 200
    from buyeros_api.marketing.router import create_marketing_app
    monkeypatch.setenv("BUYEROS_MARKETING_GLOBAL_PER_HOUR", "1")
    third = challenge(api); age_challenge(third, 3)
    with TestClient(create_marketing_app()) as restarted:
        response = post(restarted, payload(third))
        assert response.status_code == 429
        assert response.json() == {"code": "rate_limited", "retryable": True}


