def headers(**values):
    return {"Origin": ORIGIN, "X-Marketing-Gateway-Key": os.environ["BUYEROS_MARKETING_GATEWAY_KEY"], **values}


def challenge(api):
    response = api.get("/marketing/leads/challenge", headers=headers())
    assert response.status_code == 200, response.text
    return response.json()["challenge_id"]


def payload(challenge_id, **values):
    return {"name": "Synthetic Buyer", "email": f"buyer-{uuid4().hex}@example.test",
            "company": "Sample Company", "message": "Synthetic demonstration only.",
            "locale": "en", "challenge_id": challenge_id, "website": "", **values}


def post(api, body, key=None):
    return api.post("/marketing/leads", json=body,
                    headers=headers(**{"Idempotency-Key": key or str(uuid4())}))


def age_challenge(challenge_id, seconds):
    # Only the proved owner fixture may manipulate synthetic challenge timing.
    with psycopg.connect(os.environ["BUYEROS_MARKETING_TEST_OWNER_DSN"]) as connection:
        connection.execute("UPDATE marketing_intake.challenges SET issued_at = clock_timestamp() - %s * interval '1 second', expires_at = clock_timestamp() + (900 - %s) * interval '1 second' WHERE id=%s",
                           (seconds, seconds, challenge_id))


@pytest.mark.parametrize("method,path", [("GET", "/marketing/leads/challenge"), ("POST", "/marketing/leads")])
def test_foreign_or_missing_origin_and_gateway_are_denied_before_sql(api, method, path, monkeypatch):
    def forbidden(*args, **kwargs):
        raise AssertionError("untrusted boundary reached SQL")
    monkeypatch.setattr(psycopg, "connect", forbidden)
    for supplied in ({}, {"Origin": ORIGIN}, headers(Origin="https://foreign.test"),
                     headers(Origin=ORIGIN + "/"), headers(**{"X-Marketing-Gateway-Key": "wrong"}),
                     headers(Origin="null"), headers(Origin=ORIGIN + ", https://foreign.test")):
        response = api.request(method, path, headers=supplied, json={})
        assert response.status_code == 403
        assert response.json() == {"code": "forbidden", "retryable": False}


@pytest.mark.parametrize("body,key", [
    ({"name": "n" * 121}, None), ({"company": "c" * 161}, None),
    ({"message": "m" * 2001}, None), ({"email": "a" * 250 + "@x.test"}, None),
    ({"email": "real@example.com"}, None), ({"email": "not-an-email"}, None),
    ({"name": "  "}, None), ({"locale": "fr"}, None), ({"unexpected": True}, None),
    ({"website": "https://spam.test"}, None), ({}, "not-a-uuid"),
])
def test_invalid_payloads_never_reach_store(api, body, key, monkeypatch):
    def forbidden(*args, **kwargs):
        raise AssertionError("invalid payload reached SQL")
    monkeypatch.setattr(psycopg, "connect", forbidden)
    response = post(api, payload(str(uuid4()), **body), key)
    assert response.status_code == 422
    assert response.json()["retryable"] is False


def test_body_limit_stream_and_content_type(api, monkeypatch):
    def forbidden(*args, **kwargs):
        raise AssertionError("oversized or malformed body reached SQL")
    monkeypatch.setattr(psycopg, "connect", forbidden)
    common = headers(**{"Idempotency-Key": str(uuid4()), "Content-Type": "application/json"})
    for body in (b" " * 8193, b"{invalid", b"[]"):
        response = api.post("/marketing/leads", content=body, headers=common)
        assert response.status_code == 422
    streamed = api.post("/marketing/leads", content=iter([b" " * 4096, b" " * 4097]), headers=common)
    assert streamed.status_code == 422
    response = api.post("/marketing/leads", content=b"{}", headers=headers())
    assert response.status_code == 422


def test_challenge_age_expiry_and_unissued_challenge(api):
    challenge_id = challenge(api)
    body = payload(challenge_id)
    assert post(api, body).json() == {"code": "challenge_invalid", "retryable": False}
    age_challenge(challenge_id, 901)
    assert post(api, body).status_code == 422
    assert post(api, payload(str(uuid4()))).status_code == 422


def test_committed_receipt_survives_restart_and_lost_response_retry(api):
    challenge_id = challenge(api)
    age_challenge(challenge_id, 3)
    body, key = payload(challenge_id), str(uuid4())
    response = post(api, body, key)
    assert response.status_code == 201
    ack = response.json()
    assert ack["status"] == "received" and ack["synthetic"] is True
    with psycopg.connect(os.environ["BUYEROS_MARKETING_TEST_OWNER_DSN"]) as connection:
        saved = connection.execute("SELECT id::text, email, locale, synthetic FROM marketing_intake.leads WHERE id=%s", (ack["receipt_id"],)).fetchone()
    assert saved == (ack["receipt_id"], body["email"], "en", True)
    # Fresh app/store instance observes the committed row, even after challenge expiry.
    age_challenge(challenge_id, 901)
    from buyeros_api.marketing.router import create_marketing_app
    with TestClient(create_marketing_app()) as restarted:
        retried = post(restarted, body, key)
        assert retried.status_code == 200 and retried.json() == ack
        assert post(restarted, {**body, "message": "Changed request"}, key).status_code == 409
        assert post(restarted, body).status_code == 422


